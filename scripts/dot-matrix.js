function renderDotMatrix(text, options = {}) {
  const pitch = options.pitch || 10;
  const radius = options.radius || 3.6;
  const rows = 7;
  const upper = text.toUpperCase();
  const cols = [];

  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i];
    const g = GLYPHS[ch] || GLYPHS[' '];
    const width = g[0].length;
    for (let c = 0; c < width; c++) {
      cols.push({
        bits: g.map(row => row[c] === '1'),
        hot: ch === '.' || (options.hotIndex !== undefined && i === options.hotIndex)
      });
    }
    if (i < upper.length - 1) {
      cols.push({ bits: new Array(rows).fill(false), hot: false });
    }
  }

  const width = cols.length * pitch;
  const height = rows * pitch;
  let circles = '';

  cols.forEach((col, x) => {
    col.bits.forEach((on, y) => {
      if (!on) return;
      const jitter = (((x + 1) * 73856093) ^ ((y + 1) * 19349663)) >>> 0;
      const delay = x * 15 + (jitter % 160);
      const hotClass = col.hot ? ' hot' : '';
      circles += `<circle class="on${hotClass}" cx="${x * pitch + pitch / 2}" cy="${y * pitch + pitch / 2}" r="${radius}" style="--d:${delay}ms"/>`;
    });
  });

  return `<svg class="sp-mx" viewBox="0 0 ${width} ${height}" focusable="false" aria-hidden="true"><defs><pattern id="sp-grid" width="${pitch}" height="${pitch}" patternUnits="userSpaceOnUse"><circle cx="${pitch / 2}" cy="${pitch / 2}" r="${radius}"/></pattern></defs><rect class="off" width="${width}" height="${height}" fill="url(#sp-grid)"/>${circles}</svg>`;
}

